enum AppLanguage {
  english('en', 'English', 'English', Locale('en')),
  simplifiedChinese('zh-CN', 'Simplified Chinese', '简体中文', Locale('zh', 'CN')),
  traditionalChinese(
    'zh-TW',
    'Traditional Chinese',
    '繁體中文',
    Locale('zh', 'TW'),
  );

  const AppLanguage(this.code, this.name, this.nativeName, this.locale);

  final String code;
  final String name;
  final String nativeName;
  final Locale locale;

  static AppLanguage fromCode(String? code) {
    return AppLanguage.values.firstWhere(
      (language) => language.code == code,
      orElse: () => AppLanguage.english,
    );
  }
}

final i18nProvider = NotifierProvider<I18nNotifier, AppLanguage>(
  I18nNotifier.new,
);

final translationsProvider = Provider<AppTranslations>((ref) {
  final language = ref.watch(i18nProvider);
  return AppTranslations(language);
});

class I18nNotifier extends Notifier<AppLanguage> {
  static const _languageKey = 'app_language';

  @override
  AppLanguage build() {
    _loadSavedLanguage();
    return _detectDeviceLanguage();
  }

  Future<void> setLanguage(AppLanguage language) async {
    state = language;
    final preferences = await SharedPreferences.getInstance();
    await preferences.setString(_languageKey, language.code);
  }

  Future<void> _loadSavedLanguage() async {
    final preferences = await SharedPreferences.getInstance();
    final savedLanguage = preferences.getString(_languageKey);
    if (savedLanguage != null) {
      state = AppLanguage.fromCode(savedLanguage);
      return;
    }

    await preferences.setString(_languageKey, state.code);
  }

  AppLanguage _detectDeviceLanguage() {
    final locale = PlatformDispatcher.instance.locale;
    if (locale.languageCode != 'zh') {
      return AppLanguage.english;
    }

    final scriptCode = locale.scriptCode?.toLowerCase();
    final countryCode = locale.countryCode?.toUpperCase();
    if (scriptCode == 'hant' || countryCode == 'TW' || countryCode == 'HK') {
      return AppLanguage.traditionalChinese;
    }

    return AppLanguage.simplifiedChinese;
  }
}

class AppTranslations {
  const AppTranslations(this.language);

  final AppLanguage language;

  String call(String key) =>
      _localizedValues[language]?[key] ?? _en[key] ?? key;
}

String appT(BuildContext context, String key) {
  return ProviderScope.containerOf(
    context,
    listen: false,
  ).read(translationsProvider).call(key);
}

